# Tenemos varias formas de crear condiciones o encadenarlas
# Tenemos operadores logicos y matematicos

# Operadores matematicos
# a + b = c <- operador de suma
# a - b = c <- operador de resta
# a * b = c <- operador de multiplicacion
# a / b = c <- operador de division
# a % b = c <- operador de modulo

# modulo =
# 20 / 6 = 3
# 20 % 6 = 2

# El modulo es el resto de la division entera de un numero por el otro


# Operadores logicos

# AND
# 3 + 2 == 5 and 2 - 1 == 1 ESTO ES TRUE porque ambos son True
print(True and True) # True
print(True and False) # False
print(False and True) # False
print(False and False) # False

# OR
# 3 + 2 == 1 or 1 + 1 == 2
print(True or True) # True
print(True or False) # True
print(False or True) # True
print(False or False) # False

# NOT
print(not True) # False
print(not False) # True


# Operadores de comparacion

print(3 < 5) # Operador menor que, en este caso da True
print(3 <= 3) # Operador menos igual que, en esta caso da True
print(5 > 3) # Operador mayor que, da True
print(5 >= 3) # Operador mayor igual que, da False