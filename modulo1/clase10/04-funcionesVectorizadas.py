import numpy as np

arr = np.array([10, 20, 30, 40, 50])
print("Array original: ", arr)
print("Array sumado 5: ", arr + 5)
print("Array multiplicado por 2: ", arr * 2)

# Funciones Estadisticas
print("Suma")
print(np.sum(arr))
print("Media")
print(np.mean(arr))
print("Desviacion estandar")
print(np.std(arr))
print("Maximo")
print(np.max(arr))
print("Minimo")
print(np.min(arr))

